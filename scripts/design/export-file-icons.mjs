import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';
import {icons,filenames,svg} from './file-icons-spec.mjs';
import {rasterKey,generatedKeys} from './file-icons-v15.mjs';
const root=resolve(import.meta.dir,'../..'),check=process.argv.includes('--check');
const variant=s=>s.split('-').map(w=>w[0].toUpperCase()+w.slice(1)).join('');
const quote=JSON.stringify,exts=new Set();
for(const i of icons)for(const e of i.extensions){if(exts.has(e))throw Error('Duplicate extension '+e);exts.add(e);}
async function emit(path,content){if(check){if(await readFile(path,'utf8')!==content)throw Error('Generated asset stale '+path);}else await writeFile(path,content);}
await mkdir(resolve(root,'assets/file-types'),{recursive:true});
let rust='// Generated by scripts/design/export-file-icons.mjs. Edit the v14 design source.\n';
rust+='#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum FileIcon {\n'+icons.map(i=>'    '+variant(i.key)+',').join('\n')+'\n}\nimpl FileIcon {\n';
rust+='    pub fn asset(self, dark: bool) -> &\'static str {\n        match (self, dark) {\n';
for(const i of icons)for(const dark of [false,true]){
 const name=`${i.key}${dark?'-dark':''}.svg`,data=svg(i,dark);
 if(data!==await readFile(resolve(root,'design/v14/icons',name),'utf8'))throw Error('Design/native artwork mismatch '+name);
 const asset=`file-types-generated/runtime/${rasterKey(i.key)}.png`;
 rust+=`            (Self::${variant(i.key)}, ${dark}) => "${asset}",\n`;
}
rust+='        }\n    }\n    pub(super) fn from_extension(value: &str) -> Self {\n        match value {\n';
for(const i of icons.filter(i=>i.extensions.length))rust+='            '+i.extensions.map(quote).join(' | ')+` => Self::${variant(i.key)},\n`;
rust+='            _ => Self::Generic,\n        }\n    }\n    pub(super) fn from_filename(value: &str) -> Option<Self> {\n';
for(const [name,key]of Object.entries(filenames))rust+=`        if value.eq_ignore_ascii_case(${quote(name)}) { return Some(Self::${variant(key)}); }\n`;
rust+='        None\n    }\n}\npub fn asset_bytes(path: &str) -> Option<&\'static [u8]> {\n    match path {\n';
for(const key of generatedKeys)rust+=`        "file-types-generated/runtime/${key}.png" => Some(include_bytes!("../assets/file-types-generated/runtime/${key}.png")),\n`;
rust+='        _ => None,\n    }\n}\n';
// rustfmt is used here so --check compares the actual committed generated source.
const child=Bun.spawn(['rustfmt','--edition','2024'],{stdin:new TextEncoder().encode(rust),stdout:'pipe',stderr:'pipe'});
const formatted=await new Response(child.stdout).text();if(await child.exited)throw Error(await new Response(child.stderr).text());
await emit(resolve(root,'src/file_icons_generated.rs'),formatted);
await emit(resolve(root,'design/v15/coverage.json'),JSON.stringify({families:icons.map(i=>({...i,runtimeArtwork:rasterKey(i.key)})),filenames,extensionCount:exts.size,generatedAssets:generatedKeys.length},null,2));
console.log(JSON.stringify({checked:check,families:icons.length,generatedAssets:generatedKeys.length,extensions:exts.size}));
